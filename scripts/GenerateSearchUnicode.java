// Generates Character properties needed by Rebased's NameUtilCore and matcher.
// Run with the reference JetBrains Runtime; no Java runtime is shipped in the app.
import java.io.*;
import java.nio.file.*;
public class GenerateSearchUnicode {
  static void u16(OutputStream out, int v) throws IOException { out.write(v); out.write(v >>> 8); }
  static void u32(OutputStream out, int v) throws IOException { u16(out,v); u16(out,v >>> 16); }
  static int flags(int cp) {
    int f = (Character.isUpperCase(cp) ? 1 : 0) | (Character.isLowerCase(cp) ? 2 : 0)
      | (Character.isDigit(cp) ? 4 : 0) | (Character.isLetter(cp) ? 8 : 0)
      | (Character.isIdeographic(cp) ? 16 : 0)
      | (Character.isWhitespace(cp) || Character.isSpaceChar(cp) ? 32 : 0);
    int script = switch (Character.UnicodeScript.of(cp)) {
      case COMMON -> 0; case HIRAGANA -> 1; case KATAKANA -> 2; default -> 3;
    };
    return f | script << 6;
  }
  public static void main(String[] args) throws Exception {
    Path directory = Path.of(args[0]); Files.createDirectories(directory);
    int ranges = 0, cases = 0;
    try (OutputStream out = new BufferedOutputStream(Files.newOutputStream(directory.resolve("unicode-properties.bin")))) {
      int start = 0, previous = flags(0);
      for (int cp = 1; cp <= 0x110000; cp++) {
        int f = cp == 0x110000 ? -1 : flags(cp);
        if (f != previous) {
          u32(out,start); u32(out,cp); out.write(previous); ranges++;
          start = cp; previous = f;
        }
      }
    }
    try (OutputStream out = new BufferedOutputStream(Files.newOutputStream(directory.resolve("unicode-char-case.bin")))) {
      for (int c = 0; c <= 0xffff; c++) {
        char lower = Character.toLowerCase((char)c), upper = Character.toUpperCase((char)c);
        if (lower != c || upper != c) { u16(out,c); u16(out,lower); u16(out,upper); cases++; }
      }
    }
    String metadata = "Generated by scripts/GenerateSearchUnicode.java using Java Character APIs.\n"
      + "Reference: Rebased 4aec352 NameUtilCore.kt / CodePoint.kt and MinusculeMatcherImpl.kt.\n"
      + "Runtime: " + System.getProperty("java.runtime.version") + "; vendor: " + System.getProperty("java.vendor") + "\n"
      + "This observed IDEA runtime is not proof of the installed Rebased runtime version.\n"
      + "Property records: u32le start, u32le exclusive end, u8 flags.\n"
      + "Flags: upper=1, lower=2, decimal digit=4, letter=8, ideographic=16, Kotlin whitespace=32;\n"
      + "top two bits: Common=0, Hiragana=1, Katakana=2, other=3.\n"
      + "Case records: u16le UTF-16 unit, u16le simple lower, u16le simple upper; unchanged units omitted.\n"
      + ranges + " property ranges; " + cases + " case records.\n";
    Files.writeString(directory.resolve("UNICODE-SOURCE.txt"),metadata);
    System.out.println(metadata);
  }
}
