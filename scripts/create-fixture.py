"""Create a deterministic, disposable Git repo for UI and memory checks."""
import pathlib, subprocess, sys
root = pathlib.Path(sys.argv[1]).resolve()
if root.exists():
    raise SystemExit(f'Refusing to replace existing directory: {root}')
root.mkdir(parents=True)
def git(*args):
    return subprocess.check_output(['git', '-C', str(root), *args], stderr=subprocess.STDOUT)
def write(name, text):
    path = root / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8')
def commit(message):
    git('add', '--all')
    git('-c', 'commit.gpgsign=false', 'commit', '-m', message)
git('init', '-b', 'main')
git('config', 'user.name', 'Alex Chen')
git('config', 'user.email', 'alex@example.invalid')
write('src/cache.rs', 'use std::collections::HashMap;\n\npub struct Cache {\n    entries: HashMap<String, String>,\n}\n\nimpl Cache {\n    pub fn new() -> Self {\n        Self { entries: HashMap::new() }\n    }\n\n    pub fn get(&self, key: &str) -> Option<&String> {\n        self.entries.get(key)\n    }\n}\n')
write('README.md', '# Cache service\n\nA small cache used by the API.\n')
commit('Initialize cache service')
git('checkout', '-b', 'feature/cache-limit')
path = root / 'src/cache.rs'
text = path.read_text().replace('    entries:', '    // Keep memory bounded / 限制缓存大小\n    entries:', 1).replace('    pub fn get', '    pub fn clear(&mut self) {\n        self.entries.clear();\n    }\n\n    pub fn get')
path.write_text(text)
commit('Add cache eviction support')
write('tests/cache.rs', '#[test]\nfn cache_starts_empty() {\n    assert!(true);\n}\n')
commit('Cover empty cache behavior')
git('checkout', 'main')
write('docs/review.md', '# Review notes\n\nCheck bounded memory and cancellation.\n')
commit('Document review workflow')
git('merge', '--no-ff', 'feature/cache-limit', '-m', 'Merge cache memory improvements')
git('update-ref', 'refs/remotes/origin/main', 'HEAD')
git('checkout', '-b', 'feature/ai-review')
path.write_text(path.read_text().replace('self.entries.get(key)', 'self.entries.get(key.trim())'))
commit('Normalize cache keys before lookup')
write('src/config.rs', '// Generated by AI — pending review\npub const MAX_ENTRIES: usize = 4096;\n')
write('README.md', '# Cache service\n\nA bounded cache used by the API.\n')
git('add', 'README.md')
path.write_text(path.read_text().replace('key.trim()', 'key.trim_start()'))
print(root)
