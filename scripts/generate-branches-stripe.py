"""Outline the bundled Inter label: GPUI cannot rotate ordinary text elements.
Development-only dependency: fontTools. Font license: assets/fonts/Inter-LICENSE.txt.
"""
from pathlib import Path
import argparse
import hashlib
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--chinese-font', type=Path,
                    help='Generate the Chinese label from Noto Sans CJK SC Regular 2.004')
args = parser.parse_args()
font_path = args.chinese_font or root / 'assets/fonts/Inter-Regular.otf'
if args.chinese_font and hashlib.sha256(font_path.read_bytes()).hexdigest() != '2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b':
    parser.error('Expected the Noto Sans CJK SC Regular font recorded in assets/fonts/SOURCE.txt')
font = TTFont(font_path)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
scale = 12 / font['head'].unitsPerEm
pen = SVGPathPen(glyphs)
x = 0
for ch in ('分支' if args.chinese_font else 'Branches'):
    name = cmap[ord(ch)]
    glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, 12)))
    x += glyphs[name].width * scale
height = 24 if args.chinese_font else 60
name = 'branches-stripe-zh.svg' if args.chinese_font else 'branches-stripe.svg'
source = 'Noto Sans CJK SC Regular, Copyright 2014-2021 Adobe' if args.chinese_font else 'Inter Regular'
(root / 'assets/ui' / name).write_text(
    f'<svg xmlns="http://www.w3.org/2000/svg" width="14" height="{height}" viewBox="0 0 14 {height}">'
    f'<!-- {source} outlines, SIL OFL 1.1; generated by scripts/generate-branches-stripe.py -->'
    f'<path transform="translate(0 {height}) rotate(-90)" d="{pen.getCommands()}"/></svg>\n', encoding='utf-8')
